import Recorder from '../components/Recorder'
import { useCallback, useEffect, useRef, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { api, errMsg } from '../api'
import { useAuth } from '../auth'
import { Badge, Empty, ErrorBox, Loading } from '../components/ui'


const ALLOWED = ['.mp3', '.wav', '.m4a', '.ogg', '.webm']
const MAX_MB = 50

function Card({ title, children }) {
  return (
    <section className="rounded-xl border border-gray-200 bg-white p-5">
      <h2 className="mb-3 text-sm font-semibold uppercase tracking-wide text-gray-500">{title}</h2>
      {children}
    </section>
  )
}

function Output({ out, names, isMgr }) {
  return (
    <div className="space-y-4">
      {out.generated_by === 'mock' && (
        <div className="rounded-lg border border-amber-300 bg-amber-50 p-3 text-sm text-amber-800">
          MOCK output from the development adapter. This was NOT produced by Gemini.
        </div>
      )}
      {out.generated_by === 'gemini' && (
        <p className="text-xs text-gray-500">Generated by Gemini ({out.model_name}). AI output can contain mistakes.</p>
      )}
      <div><h3 className="font-medium">Summary</h3><p className="whitespace-pre-wrap text-sm text-gray-700">{out.summary}</p></div>
      <div><h3 className="font-medium">Minutes of meeting (draft)</h3><p className="whitespace-pre-wrap text-sm text-gray-700">{out.mom}</p></div>
      <div>
        <h3 className="font-medium">Key discussion points</h3>
        <ul className="list-disc pl-5 text-sm text-gray-700">{out.discussion_points.map((p, i) => <li key={i}>{p}</li>)}</ul>
      </div>
      <div>
        <h3 className="font-medium">Key decisions</h3>
        <ul className="list-disc pl-5 text-sm text-gray-700">{out.decisions.map((p, i) => <li key={i}>{p}</li>)}</ul>
      </div>
      <div>
        <h3 className="mb-2 font-medium">Action items</h3>
        {out.action_items.length === 0 && <Empty text="No action items." />}
        <div className="space-y-2">
          {out.action_items.map((a, i) => (
            <div key={i} className={`rounded-lg border p-3 text-sm ${a.discard ? 'opacity-50' : ''} ${a.needs_review ? 'border-amber-300 bg-amber-50' : 'border-gray-200'}`}>
              <div className="flex flex-wrap items-center gap-2">
                <span className="font-medium">{a.title}</span>
                <Badge value={a.priority} />
                {a.needs_review && <span className="text-xs text-amber-700">Needs review</span>}
                {a.discard && <span className="text-xs text-gray-500">Discarded</span>}
              </div>
              {a.description && <p className="mt-1 text-gray-700">{a.description}</p>}
              <p className="mt-1 text-gray-500">
                Assignee: {names[a.assignee_id] || 'Unresolved'} · Deadline: {a.deadline || 'Not set'}
              </p>
              {a.uncertainty_note && <p className="mt-1 text-amber-700">Note: {a.uncertainty_note}</p>}
              {isMgr && a.source_context && <p className="mt-1 text-xs italic text-gray-500">Source: {a.source_context}</p>}
            </div>
          ))}
        </div>
      </div>
    </div>
  )
}

export default function MeetingDetail() {
  const { id } = useParams()
  const { user } = useAuth()
  const isMgr = user.role === 'MANAGER'
  const [m, setM] = useState(null)
  const [out, setOut] = useState(null)
  const [tasks, setTasks] = useState([])
  const [tr, setTr] = useState(null)
  const [trErr, setTrErr] = useState('')
  const [err, setErr] = useState('')
  const [upErr, setUpErr] = useState('')
  const [uploading, setUploading] = useState(false)
  const fileRef = useRef()

  const load = useCallback(async () => {
    try {
      const { data } = await api.get(`/meetings/${id}/`)
      setM(data)
      const [o, t] = await Promise.all([
        api.get(`/meetings/${id}/output/`),
        api.get('/tasks/', { params: { meeting: id } }),
      ])
      setOut(o.data)
      setTasks(t.data.results)
    } catch (e) {
      setErr(errMsg(e))
    }
  }, [id])

  useEffect(() => { load() }, [load])

  // Poll while the backend pipeline is running
  useEffect(() => {
    if (m?.status !== 'PROCESSING') return
    const t = setInterval(load, 3000)
    return () => clearInterval(t)
  }, [m?.status, load])

  const upload = async (file) => {
    setUpErr('')
    if (!file) return
    const ext = '.' + file.name.split('.').pop().toLowerCase()
    if (!ALLOWED.includes(ext)) return setUpErr(`Unsupported format. Allowed: ${ALLOWED.join(', ')}`)
    if (file.size > MAX_MB * 1024 * 1024) return setUpErr(`File too large. Max ${MAX_MB} MB.`)
    const fd = new FormData()
    fd.append('audio', file)
    setUploading(true)
    try {
      await api.post(`/meetings/${id}/upload-audio/`, fd)
      setTr(null)
      await load()
    } catch (e) {
      setUpErr(errMsg(e))
    } finally {
      setUploading(false)
      if (fileRef.current) fileRef.current.value = ''
    }
  }

  const loadTranscript = async () => {
    setTrErr('')
    try {
      const { data } = await api.get(`/meetings/${id}/transcript/`)
      setTr(data)
    } catch (e) {
      setTrErr(errMsg(e))
    }
  }

  if (err) return <ErrorBox msg={err} />
  if (!m) return <Loading />

  const names = Object.fromEntries(m.participants.map((p) => [p.id, p.name]))
  const canUpload = isMgr && ['DRAFT', 'FAILED', 'REJECTED'].includes(m.status)
  const canReview = isMgr && ['PENDING_REVIEW', 'REJECTED'].includes(m.status)

  return (
    <div className="space-y-4">
      <Link to="/meetings" className="text-sm text-blue-700 hover:underline">← Back to meetings</Link>
      <div className="flex flex-wrap items-center gap-3">
        <h1 className="text-2xl font-semibold text-blue-950">{m.title}</h1>
        <Badge value={m.status} />
        {m.is_confidential && <span className="rounded bg-gray-800 px-2 py-0.5 text-xs text-white">Confidential</span>}
      </div>

      <Card title="Details">
        <p className="text-sm text-gray-700">{new Date(m.scheduled_at).toLocaleString()} · Manager: {m.manager_name}</p>
        {m.project_name && (
          <p className="mt-2 text-sm text-gray-600">
            Project:{' '}
            {isMgr && m.project ? (
              <Link to={`/projects/${m.project}`} className="font-medium text-blue-700 hover:underline">{m.project_name}</Link>
            ) : m.project_name}
          </p>
        )}
        {m.description && <p className="mt-2 whitespace-pre-wrap text-sm text-gray-700">{m.description}</p>}
        <p className="mt-3 text-sm text-gray-500">
          Participants: {m.participants.map((p) => p.name).join(', ') || 'None'}
        </p>
      </Card>

      {m.status === 'FAILED' && <ErrorBox msg={m.processing_error || 'Processing failed.'} />}

      {m.status === 'PROCESSING' && (
        <div className="flex items-center gap-3 rounded-xl border border-amber-300 bg-amber-50 p-4 text-sm text-amber-800">
          <div className="h-5 w-5 animate-spin rounded-full border-2 border-amber-600 border-t-transparent" />
          Processing: transcription, PII masking and AI analysis. This page updates automatically.
        </div>
      )}

      {canReview && (
        <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-blue-200 bg-blue-50 p-4">
          <span className="text-sm text-blue-900">
            {m.status === 'REJECTED' ? 'This output was rejected. You can revise and resubmit it.' : 'AI-generated draft is waiting for your review. No tasks exist until you approve.'}
          </span>
          <Link to={`/meetings/${m.id}/review`} className="rounded-lg bg-blue-700 px-4 py-2 text-sm font-medium text-white hover:bg-blue-800">
            Review and approve
          </Link>
        </div>
      )}

      {isMgr && (
        <Card title="Audio recording">
          {canUpload ? (
            <div className="space-y-2">
                <Recorder disabled={uploading} onRecorded={upload} />
              <input
                ref={fileRef}
                type="file"
                accept={ALLOWED.join(',')}
                disabled={uploading}
                onChange={(e) => upload(e.target.files[0])}
                className="block w-full text-sm text-gray-700 file:mr-3 file:rounded-lg file:border-0 file:bg-blue-700 file:px-4 file:py-2 file:text-white"
              />
              <p className="text-xs text-gray-500">Allowed: {ALLOWED.join(', ')} · max {MAX_MB} MB</p>
              {uploading && <Loading text="Uploading..." />}
              <ErrorBox msg={upErr} />
            </div>
          ) : (
            <p className="text-sm text-gray-500">
              {m.has_audio ? 'Audio uploaded.' : 'No audio uploaded.'} Uploading is available while the meeting is a draft, failed, or rejected.
            </p>
          )}
        </Card>
      )}

      <Card title="Transcript">
        {!tr && <button onClick={loadTranscript} className="rounded-lg border border-gray-300 px-4 py-2 text-sm hover:bg-gray-100">View transcript</button>}
        <ErrorBox msg={trErr} />
        {tr && !tr.available && <p className="text-sm text-gray-500">No transcript yet.</p>}
        {tr?.available && (
          <div className="space-y-3">
            {tr.source === 'dev_adapter' && (
              <div className="rounded-lg border border-amber-300 bg-amber-50 p-3 text-sm text-amber-800">
                DEV ADAPTER: this is fixed sample text. The uploaded audio was NOT transcribed by Whisper.
              </div>
            )}
            {tr.source === 'whisper' && <p className="text-xs text-gray-500">Transcribed by Whisper.</p>}
            {tr.original !== undefined && (
              <div>
                <h3 className="text-sm font-medium">Original (restricted, manager only)</h3>
                <pre className="whitespace-pre-wrap rounded-lg bg-gray-50 p-3 text-sm">{tr.original}</pre>
              </div>
            )}
            <div>
              <h3 className="text-sm font-medium">Sanitized (what the AI receives)</h3>
              <pre className="whitespace-pre-wrap rounded-lg bg-gray-50 p-3 text-sm">{tr.sanitized}</pre>
              <p className="mt-1 text-xs text-gray-500">PII masking is best-effort and may not catch everything.</p>
            </div>
          </div>
        )}
      </Card>

      <Card title="AI-generated summary and MoM">
        {out ? <Output out={out} names={names} isMgr={isMgr} /> : (
          <Empty text={isMgr ? 'No AI output yet. Upload audio to generate it.' : 'Approved outputs will appear here.'} />
        )}
      </Card>

      <Card title="Tasks from this meeting">
        {tasks.length === 0 ? <Empty text="No tasks yet. Tasks are created only after the manager approves." /> : (
          <ul className="divide-y divide-gray-100 text-sm">
            {tasks.map((t) => (
              <li key={t.id} className="flex flex-wrap items-center justify-between gap-2 py-2">
                <Link to={`/tasks/${t.id}`} className="font-medium text-blue-700 hover:underline">{t.title}</Link>
                <span className="flex items-center gap-2 text-gray-500">{t.assignee_name} · {t.deadline || 'No deadline'} <Badge value={t.status} /></span>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </div>
  )
}