import re

from rest_framework import serializers
from rest_framework_simplejwt.serializers import TokenObtainPairSerializer
from .access import ALL_CODES, base_for
from .models import Role, User

PHONE_LENGTH = 11  # digits only; keep in sync with PHONE_LENGTH in the frontend constants.js


def clean_phone(value):
    value = (value or "").strip()
    if value and not re.fullmatch(rf"\d{{{PHONE_LENGTH}}}", value):
        raise serializers.ValidationError(f"Phone number must be exactly {PHONE_LENGTH} digits.")
    return value


class LoginSerializer(TokenObtainPairSerializer):
    @classmethod
    def get_token(cls, user):
        token = super().get_token(user)
        token["role"] = user.role
        return token

    def validate(self, attrs):
        ident = attrs.get(self.username_field, "")
        if "@" in ident:
            match = User.objects.filter(email__iexact=ident).first()
            if match:
                attrs[self.username_field] = match.username
        data = super().validate(attrs)
        data["user"] = UserSerializer(self.user).data
        return data


class UserSerializer(serializers.ModelSerializer):
    name = serializers.CharField(source="display_name", read_only=True)
    # `role` is the base access level (ADMIN / MANAGER / EMPLOYEE); it follows the chosen role.
    role = serializers.CharField(read_only=True)
    role_id = serializers.PrimaryKeyRelatedField(source="role_ref", queryset=Role.objects.all(), required=False)
    role_name = serializers.CharField(read_only=True)
    permissions = serializers.SerializerMethodField()
    permission_overrides = serializers.JSONField(required=False)
    can_create_meetings = serializers.SerializerMethodField()

    class Meta:
        model = User
        fields = ["id", "username", "email", "first_name", "last_name", "name",
                  "role", "role_id", "role_name", "permissions", "permission_overrides",
                  "is_active", "date_joined", "department", "phone",
                  "must_change_password", "can_create_meetings"]
        # username is generated by the server and never edited
        read_only_fields = ["username", "date_joined", "must_change_password"]
        extra_kwargs = {
            "email": {"required": True, "allow_blank": False},
            "first_name": {"required": True, "allow_blank": False},
            "last_name": {"required": True, "allow_blank": False},
        }

    def get_permissions(self, obj):
        return sorted(obj.permission_set())

    def get_can_create_meetings(self, obj):
        return obj.can_create_meetings

    def to_representation(self, instance):
        data = super().to_representation(instance)
        data["permission_overrides"] = instance.all_overrides()  # includes the legacy meeting override
        return data

    def validate_email(self, value):
        value = value.strip()
        clash = User.objects.filter(email__iexact=value)
        if self.instance is not None:
            clash = clash.exclude(pk=self.instance.pk)
        if clash.exists():
            raise serializers.ValidationError("A user with this email already exists.")
        return value

    def validate_phone(self, value):
        return clean_phone(value)

    def validate_role_id(self, role):
        # Admins can't be created or assigned through the API.
        if role.base == "ADMIN" and not (self.instance is not None and self.instance.role == "ADMIN"):
            raise serializers.ValidationError("Admin accounts cannot be created or assigned here.")
        return role

    def validate_permission_overrides(self, value):
        if not isinstance(value, dict):
            raise serializers.ValidationError("Must be an object of permission code to true/false.")
        clean = {}
        for code, allowed in value.items():
            if code not in ALL_CODES:
                raise serializers.ValidationError(f"Unknown permission: {code}")
            if not isinstance(allowed, bool):
                raise serializers.ValidationError(f"{code} must be true or false.")
            clean[code] = allowed
        return clean

    def validate(self, attrs):
        role = attrs.get("role_ref")
        if role is None and self.instance is None:
            # Older clients send the plain role string instead of a role id.
            key = (self.initial_data.get("role") or "EMPLOYEE").upper()
            if key not in ("MANAGER", "EMPLOYEE"):
                raise serializers.ValidationError({"role_id": "Admin accounts cannot be created or assigned here."})
            role = Role.objects.filter(base=key).order_by("-is_system", "id").first()
            if role is not None:
                attrs["role_ref"] = role
            else:
                attrs["role"] = key
        if role is not None:
            attrs["role"] = role.base
        return attrs

    def create(self, validated):
        # username and password are generated by the view and passed via serializer.save(...)
        pw = validated.pop("password", None)
        if not pw:
            raise serializers.ValidationError({"password": "Required."})
        return User.objects.create_user(password=pw, **validated)

    def update(self, instance, validated):
        validated.pop("password", None)
        if "permission_overrides" in validated:
            instance.meeting_create_override = None  # the new overrides replace the legacy flag
        for k, v in validated.items():
            setattr(instance, k, v)
        instance.save()
        return instance


class ProfileSerializer(serializers.ModelSerializer):
    """What a user may edit about themselves. Username, email and role stay admin-controlled."""

    class Meta:
        model = User
        fields = ["first_name", "last_name", "phone", "department"]
        extra_kwargs = {
            "first_name": {"required": True, "allow_blank": False},
            "last_name": {"required": True, "allow_blank": False},
        }

    def validate_phone(self, value):
        return clean_phone(value)


class RoleSerializer(serializers.ModelSerializer):
    user_count = serializers.SerializerMethodField()

    class Meta:
        model = Role
        fields = ["id", "name", "description", "base", "permissions", "is_system", "user_count", "created_at"]
        # the workspace (base) is worked out from the permissions, never typed in
        read_only_fields = ["base", "is_system", "created_at"]

    def get_user_count(self, obj):
        annotated = getattr(obj, "user_count", None)
        return annotated if annotated is not None else obj.users.count()

    def validate_name(self, value):
        value = " ".join(value.split())
        if not value:
            raise serializers.ValidationError("Role name is required.")
        clash = Role.objects.filter(name__iexact=value)
        if self.instance is not None:
            clash = clash.exclude(pk=self.instance.pk)
        if clash.exists():
            raise serializers.ValidationError("A role with this name already exists.")
        return value

    def validate_description(self, value):
        return value.strip()

    def validate_permissions(self, value):
        if not isinstance(value, list):
            raise serializers.ValidationError("Must be a list of permission codes.")
        unknown = [c for c in value if c not in ALL_CODES]
        if unknown:
            raise serializers.ValidationError(f"Unknown permission: {unknown[0]}")
        return list(dict.fromkeys(value))  # drop duplicates, keep order

    def validate(self, attrs):
        inst = self.instance
        if inst is not None and inst.base == Role.Base.ADMIN:
            raise serializers.ValidationError("The Admin role is locked and cannot be edited.")
        return attrs

    def create(self, validated):
        validated["base"] = base_for(validated.get("permissions", []))
        return super().create(validated)

    def update(self, instance, validated):
        old_base = instance.base
        if "permissions" in validated:
            validated["base"] = base_for(validated["permissions"])
        role = super().update(instance, validated)
        if role.base != old_base:
            # keep every holder of this role on the matching base access level
            role.users.update(role=role.base)
        return role
