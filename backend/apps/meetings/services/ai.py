from datetime import timedelta
from typing import Literal, Optional
from django.conf import settings
from pydantic import BaseModel, ValidationError


class ActionItemSchema(BaseModel):
    title: str
    description: str = ""
    assignee: Optional[str] = None      # pseudonym like "P1", or null
    deadline: Optional[str] = None      # YYYY-MM-DD or null
    priority: Literal["LOW", "MEDIUM", "HIGH"] = "MEDIUM"
    confidence: Literal["LOW", "MEDIUM", "HIGH"] = "MEDIUM"
    uncertainty_note: str = ""
    source_context: str = ""


class MeetingAnalysis(BaseModel):
    summary: str
    mom: str
    discussion_points: list[str]
    decisions: list[str]
    action_items: list[ActionItemSchema]


class AIError(Exception):
    """Safe message only. Never include transcript content."""


PROMPT = """You analyze a SANITIZED meeting transcript. Participants appear as P1, P2... ; masked data appears as [EMAIL] etc.
Meeting date: {date}.
Rules:
- Do NOT invent decisions, deadlines, participants or commitments absent from the transcript.
- assignee must be a pseudonym (P1, P2...) or null if unclear. Never guess.
- deadline must be YYYY-MM-DD only if explicit or reliably inferable from the meeting date; otherwise null.
- If assignee or deadline is unclear, set confidence LOW and explain in uncertainty_note.
- source_context: a short excerpt from the transcript supporting the item.
Return JSON: summary, mom (draft minutes), discussion_points, decisions, action_items.

TRANSCRIPT:
{text}
"""


def _mock(sanitized, meeting_date):
    d = (meeting_date + timedelta(days=3)).date().isoformat()
    return MeetingAnalysis(
        summary="[MOCK] Budget report, client communication and launch timing were discussed.",
        mom="[MOCK] Draft minutes generated by the development mock adapter, not by Gemini.",
        discussion_points=["[MOCK] Budget report", "[MOCK] Launch timing"],
        decisions=["[MOCK] Move the product launch to next month"],
        action_items=[
            ActionItemSchema(title="Prepare budget report", assignee="P1", deadline=d, priority="HIGH",
                             confidence="MEDIUM", source_context="P1 will prepare the budget report by Friday"),
            ActionItemSchema(title="Send final version", assignee="P2", deadline=None, confidence="LOW",
                             uncertainty_note="No deadline stated.", source_context="P2 will send the final version"),
            ActionItemSchema(title="Update the client", assignee=None, confidence="LOW",
                             uncertainty_note="Nobody confirmed who owns this."),
        ])


def analyze(sanitized, meeting_date):
    """Returns (MeetingAnalysis, generated_by, model_name)."""
    if settings.AI_ADAPTER == "mock":
        return _mock(sanitized, meeting_date), "mock", "mock"
    if not settings.GEMINI_API_KEY or not settings.GEMINI_MODEL:
        raise AIError("Gemini is not configured: set GEMINI_API_KEY and GEMINI_MODEL.")
    from google import genai
    from google.genai import errors, types
    try:
        client = genai.Client(api_key=settings.GEMINI_API_KEY)
        resp = client.models.generate_content(
            model=settings.GEMINI_MODEL,
            contents=PROMPT.format(date=meeting_date.date().isoformat(), text=sanitized),
            config=types.GenerateContentConfig(
                response_mime_type="application/json", response_schema=MeetingAnalysis, temperature=0.2))
        return MeetingAnalysis.model_validate_json(resp.text), "gemini", settings.GEMINI_MODEL
    except errors.APIError as e:
        if e.code == 404:
            raise AIError(f"Gemini model '{settings.GEMINI_MODEL}' unavailable. Fix GEMINI_MODEL in .env.")
        if e.code == 429:
            raise AIError("Gemini rate limit reached. Retry later.")
        raise AIError(f"Gemini API error (code {e.code}).")
    except (ValidationError, ValueError):
        raise AIError("Gemini returned a malformed response.")